# [1차]: 체이닝 기반 해시맵 모듈을 정의합니다.
# [2차]: 여러 개의 번호표 우편함과 서류철을 이용해 물건을 광속으로 찾아주는 수납장을 만듭니다.
"""
체이닝 기반 해시맵 (Chaining Hash Map) 모듈
dict, set, collections 없이 DoublyLinkedList를 버킷 체이닝으로 사용하여 구현합니다.
로드 팩터 0.75 초과 시 버킷을 2배 확장(Rehashing)합니다.
"""

# [1차]: 체이닝 버킷 구현에 필요한 DoublyLinkedList 및 Node 클래스를 임포트합니다.
# [2차]: 우편함 서류철에 서류를 엮어둘 이중 기차 대형 부품들을 가져옵니다.
from src.doubly_linked_list import DoublyLinkedList, Node


# [1차]: 고유 해시 함수와 체이닝, 동적 리사이징을 갖춘 HashMap 클래스를 선언합니다.
# [2차]: 내장 딕셔너리 없이 밑바닥부터 세운 대형 우편 관리소입니다.
class HashMap:
    """
    체이닝(Chaining) 방식 해시맵
    - 충돌 해결: DoublyLinkedList 체이닝
    - 해시 함수: djb2 기반 고분산 해시 알고리즘
    - 동적 리사이징: 로드 팩터 > 0.75 시 2배 확장
    """
    # [1차]: 기본 버킷 크기 상수를 16으로 정의합니다.
    # [2차]: 최초에 열어두는 우편함 개수를 16칸으로 맞춥니다.
    DEFAULT_CAPACITY = 16
    # [1차]: 버킷 리사이징 임계값인 최대 로드 팩터 상수를 0.75로 정의합니다.
    # [2차]: 우편함 공간이 75% 이상 차면 칸을 늘리겠다는 안전 기준선입니다.
    MAX_LOAD_FACTOR = 0.75

    # [1차]: HashMap 객체를 초기화하며 버킷 배열을 설정합니다.
    # [2차]: 우편함들을 일렬로 세우고 장부를 0으로 초기화합니다.
    def __init__(self, initial_capacity=DEFAULT_CAPACITY):
        # [1차]: 초기 수용량(버킷 수)을 최소 4 이상으로 안전하게 보정합니다.
        # [2차]: 적어도 4칸 이상의 우편함 칸수를 보장합니다.
        self._capacity = max(initial_capacity, 4)
        # [1차]: 저장된 총 고유 키의 개수를 0으로 초기화합니다.
        # [2차]: 보관된 우편물 개수를 0개로 설정합니다.
        self._size = 0
        # [1차]: 각 버킷 인덱스마다 빈 DoublyLinkedList를 할당한 리스트를 생성합니다.
        # [2차]: 16개의 우편함 칸마다 각각 전용 서류철(연결 리스트)을 꽂아둡니다.
        self._buckets = [DoublyLinkedList() for _ in range(self._capacity)]

    # [1차]: djb2 해시 알고리즘을 사용하여 임의의 키를 32비트 양의 정수 해시코드로 변환합니다.
    # [2차]: 주민등록번호나 이름을 소수 5381과 마법의 곱셈 공식에 넣어 고유 번호표로 바꿉니다.
    def _hash(self, key):
        """
        직접 설계한 djb2 기반 해시 함수
        소수 5381과 비트 시프트 연산(h * 33 + ord(c))을 통해 균등한 해시 분포를 보장합니다.
        """
        # [1차]: 키를 문자열로 정규화합니다.
        # [2차]: 어떤 종류의 이름표든 글자로 또박또박 바꿉니다.
        key_str = str(key)
        # [1차]: djb2 알고리즘의 초기 소수 시드값 5381을 설정합니다.
        # [2차]: 마법의 계산기 기본 밑자리 숫자를 5381로 잡습니다.
        h = 5381
        # [1차]: 문자열의 각 문자를 순회합니다.
        # [2차]: 이름표의 글자를 한 글자씩 읽어갑니다.
        for char in key_str:
            # [1차]: (h * 33 + ord(char)) 연산을 비트 시프트로 수행하고 31비트 양수로 마스킹합니다.
            # [2차]: 숫자를 마구 흔들어 섞은 뒤 음수가 되지 않도록 깨끗이 정돈합니다.
            h = (((h << 5) + h) + ord(char)) & 0x7FFFFFFF
        # [1차]: 최종 계산된 해시값을 반환합니다.
        # [2차]: 골고루 흩어진 고유 번호표를 줍니다.
        return h

    # [1차]: 해시값을 현재 버킷 크기로 모듈러 연산하여 0 ~ (capacity - 1) 범위의 인덱스를 산출합니다.
    # [2차]: 번호표를 우편함 개수로 나누어 몇 번 칸에 넣을지 결정합니다.
    def _get_bucket_index(self, key):
        """해시값을 현재 버킷 크기로 모듈러 연산하여 인덱스 계산"""
        # [1차]: _hash(key) % self._capacity 연산 결과를 반환합니다.
        # [2차]: "당신 서류는 3번 우편함에 넣으세요" 하고 칸 번호를 알려줍니다.
        return self._hash(key) % self._capacity

    # [1차]: 키-값 쌍을 저장하며 기존 키는 덮어쓰고, 로드팩터 초과 시 2배 리사이징을 수행합니다.
    # [2차]: 우편함에 서류를 꽂고, 꽉 차기 직전이면 수납장을 2배 큰 새 수납장으로 교체합니다.
    def put(self, key, value):
        """
        키와 값을 해시맵에 저장합니다.
        이미 키가 존재하면 값을 덮어씁니다.
        저장 후 로드 팩터가 0.75를 초과하면 버킷을 2배 확장합니다.
        """
        # [1차]: 키가 들어갈 버킷 인덱스를 계산합니다.
        # [2차]: 몇 번 우편함으로 가야 할지 찾습니다.
        idx = self._get_bucket_index(key)
        # [1차]: 해당 인덱스의 DoublyLinkedList 버킷을 가져옵니다.
        # [2차]: 해당 칸의 서류철을 꺼냅니다.
        bucket = self._buckets[idx]

        # [1차]: 해당 버킷에 이미 동일한 키를 가진 노드가 존재하는지 선형 순회합니다.
        # [2차]: 서류철을 넘기며 이미 같은 이름표가 꽂혀 있는지 살펴봅니다.
        for node in bucket:
            # [1차]: 키가 일치하는 노드를 발견한 경우 분기합니다.
            # [2차]: 예전에 보관한 같은 이름표 서류를 찾았습니다.
            if node.key == key:
                # [1차]: 덮어쓰기 전 기존 value를 임시 저장합니다.
                # [2차]: 옛날 서류 알맹이를 잠시 메모해둡니다.
                old_val = node.value
                # [1차]: 노드의 value를 새 값으로 갱신합니다.
                # [2차]: 새 내용물로 종이를 싹 갈아 끼웁니다.
                node.value = value
                # [1차]: 노드의 data 튜플도 새 값으로 갱신합니다.
                # [2차]: 종합 선물세트 상자의 내용도 업데이트합니다.
                node.data = (key, value)
                # [1차]: 기존 값을 반환하며 종료합니다.
                # [2차]: 교체된 옛날 물건을 건네주고 끝냅니다.
                return old_val

        # [1차]: 버킷에 키가 없으므로 새 Node 객체를 생성합니다.
        # [2차]: 신규 회원의 새 서류 봉투를 만듭니다.
        new_node = Node(key=key, value=value, data=(key, value))
        # [1차]: 버킷 리스트의 맨 뒤에 새 노드를 체이닝 삽입합니다.
        # [2차]: 서류철 맨 뒷장에 새 서류 봉투를 착 꽂아 넣습니다.
        bucket.insert_back(new_node)
        # [1차]: 전체 키 개수를 1 증가시킵니다.
        # [2차]: 총 보관 서류 개수 장부를 1 올립니다.
        self._size += 1

        # [1차]: 현재 로드 팩터(size / capacity)가 0.75를 초과하는지 검사합니다.
        # [2차]: 수납장에 서류가 75% 넘게 차서 비좁아졌는지 확인합니다.
        if (self._size / self._capacity) > self.MAX_LOAD_FACTOR:
            # [1차]: 버킷 용량을 2배로 확장하고 재해싱합니다.
            # [2차]: 우편함을 2배로 넓히고 서류들을 널찍하게 다시 정리합니다.
            self._resize(self._capacity * 2)

        # [1차]: 신규 키 삽입이므로 이전 값 없음을 뜻하는 None을 반환합니다.
        # [2차]: 새로 들어온 손님이니 옛날 물건은 없다고 알립니다.
        return None

    # [1차]: 지정된 키에 연관된 값을 O(1) 평균 시간으로 조회합니다.
    # [2차]: 이름표를 보고 우편함으로 달려가 서류 내용을 꺼내 읽어줍니다.
    def get(self, key):
        """
        키에 해당하는 값을 조회합니다.
        키가 존재하지 않으면 None을 반환합니다.
        """
        # [1차]: 키의 버킷 인덱스를 계산합니다.
        # [2차]: 몇 번 우편함 칸에 있는지 번호를 찍습니다.
        idx = self._get_bucket_index(key)
        # [1차]: 해당 버킷의 연결 리스트를 가져옵니다.
        # [2차]: 그 칸의 서류철을 꺼냅니다.
        bucket = self._buckets[idx]

        # [1차]: 버킷 내 노드들을 순회하며 key가 일치하는 노드를 찾습니다.
        # [2차]: 서류철을 넘기며 일치하는 이름표를 찾습니다.
        for node in bucket:
            # [1차]: 일치하는 키를 찾으면 해당 노드의 value를 반환합니다.
            # [2차]: 찾았으면 서류 안의 내용을 읽어드립니다.
            if node.key == key:
                # [1차]: 노드의 value를 반환합니다.
                # [2차]: 알맹이를 꺼내 드립니다.
                return node.value
        # [1차]: 일치하는 키가 없으면 None을 반환합니다.
        # [2차]: 없으면 "그런 손님 서류는 없습니다" 하고 빈손으로 돌아옵니다.
        return None

    # [1차]: 키에 해당하는 Node 객체 레퍼런스 자체를 반환합니다 (LRU 연동용).
    # [2차]: 내용물뿐만 아니라 서류 봉투 자체를 통째로 가리켜줍니다.
    def get_node(self, key):
        """
        키에 해당하는 노드 참조 자체를 조회합니다 (LRU 등 내부 연동용).
        """
        # [1차]: 버킷 인덱스를 계산합니다.
        # [2차]: 칸 번호를 알아냅니다.
        idx = self._get_bucket_index(key)
        # [1차]: 버킷 연결 리스트를 참조합니다.
        # [2차]: 서류철을 꺼냅니다.
        bucket = self._buckets[idx]

        # [1차]: 버킷 내 노드를 순회합니다.
        # [2차]: 봉투를 하나씩 넘겨봅니다.
        for node in bucket:
            # [1차]: 키가 일치하면 노드 객체 자체를 반환합니다.
            # [2차]: 찾은 서류 봉투를 그대로 건넵니다.
            if node.key == key:
                # [1차]: 노드를 반환합니다.
                # [2차]: 봉투를 전달합니다.
                return node
        # [1차]: 찾지 못하면 None을 반환합니다.
        # [2차]: 없으면 없다고 합니다.
        return None

    # [1차]: 주어진 키의 노드를 버킷 체인에서 O(1)으로 분리 제거합니다.
    # [2차]: 우편함 서류철에서 해당 이름표 봉투를 쏙 뽑아 영구 파기합니다.
    def remove(self, key):
        """
        키에 해당하는 항목을 삭제하고 기존 값을 반환합니다.
        존재하지 않으면 None을 반환합니다.
        """
        # [1차]: 버킷 인덱스를 계산합니다.
        # [2차]: 우편함 번호를 확인합니다.
        idx = self._get_bucket_index(key)
        # [1차]: 해당 버킷을 가져옵니다.
        # [2차]: 서류철을 꺼냅니다.
        bucket = self._buckets[idx]

        # [1차]: 버킷 내 노드를 순회합니다.
        # [2차]: 서류를 훑어봅니다.
        for node in bucket:
            # [1차]: 삭제 대상 키를 발견한 경우 처리합니다.
            # [2차]: 파기할 서류를 발견했습니다.
            if node.key == key:
                # [1차]: 삭제될 노드의 값을 임시 저장합니다.
                # [2차]: 버리기 전에 알맹이를 확인합니다.
                val = node.value
                # [1차]: DoublyLinkedList의 remove_node로 체인에서 제거합니다.
                # [2차]: 서류철 바인더에서 해당 봉투를 똑딱 떼어냅니다.
                bucket.remove_node(node)
                # [1차]: 해시맵 총 크기를 1 차감합니다.
                # [2차]: 총 서류 개수 장부를 1 줄입니다.
                self._size -= 1
                # [1차]: 제거된 기존 값을 반환합니다.
                # [2차]: 꺼낸 알맹이를 돌려줍니다.
                return val
        # [1차]: 키가 존재하지 않으면 None을 반환합니다.
        # [2차]: 버릴 게 없으니 그냥 끝냅니다.
        return None

    # [1차]: 해시맵 내에 특정 키가 존재하는지 여부를 불리언 값으로 반환합니다.
    # [2차]: "이 사람 서류가 우리 수납장에 있나요?"라는 물음에 네/아니오로 답합니다.
    def contains(self, key):
        """키 존재 여부를 반환합니다 (True/False)."""
        # [1차]: get 결과가 None이 아니거나 _key_exists가 참인지 판별합니다.
        # [2차]: 값이 None으로 저장된 경우까지 꼼꼼히 따져 존재 여부를 답합니다.
        return self.get(key) is not None or self._key_exists(key)

    # [1차]: 값이 None인 특수 엔트리까지 정확히 키 존재를 확인하는 보조 메서드입니다.
    # [2차]: 내용물이 비어있는 빈 봉투라도 서류철에 꽂혀 있는지 돋보기로 확인합니다.
    def _key_exists(self, key):
        """값이 None인 경우에도 키 존재 여부를 판별하기 위한 헬퍼"""
        # [1차]: 인덱스를 구합니다.
        # [2차]: 칸 번호를 봅니다.
        idx = self._get_bucket_index(key)
        # [1차]: 버킷을 가져옵니다.
        # [2차]: 서류철을 봅니다.
        bucket = self._buckets[idx]
        # [1차]: 노드를 순회하며 키 일치 여부를 검사합니다.
        # [2차]: 이름표가 있는지 넘겨봅니다.
        for node in bucket:
            # [1차]: 일치하면 True를 반환합니다.
            # [2차]: 있으면 네! 하고 외칩니다.
            if node.key == key:
                # [1차]: True 반환
                # [2차]: 존재 확인
                return True
        # [1차]: 없으면 False를 반환합니다.
        # [2차]: 없으면 아니오! 라고 답합니다.
        return False

    # [1차]: 해시맵에 보관된 모든 키 목록을 수집하여 파이썬 리스트로 반환합니다.
    # [2차]: 16개 우편함의 모든 서류철을 돌며 이름표만 싹 모아 명부를 만듭니다.
    def keys(self):
        """저장된 모든 키의 목록을 일반 파이썬 리스트로 반환합니다."""
        # [1차]: 키들을 모을 빈 리스트를 생성합니다.
        # [2차]: 백지 이름표 목록을 만듭니다.
        all_keys = []
        # [1차]: 모든 버킷 연결 리스트를 순회합니다.
        # [2차]: 0번 칸부터 마지막 칸까지 순서대로 둘러봅니다.
        for bucket in self._buckets:
            # [1차]: 각 버킷 내의 노드들을 순회합니다.
            # [2차]: 각 서류철에 꽂힌 봉투들을 봅니다.
            for node in bucket:
                # [1차]: 노드의 키를 결과 리스트에 추가합니다.
                # [2차]: 이름표 글자를 명부에 한 줄씩 적습니다.
                all_keys.append(node.key)
        # [1차]: 완성된 키 리스트를 반환합니다.
        # [2차]: 완성된 전체 명부를 전달합니다.
        return all_keys

    # [1차]: 해시맵에 저장된 총 고유 키의 개수를 반환합니다.
    # [2차]: 현재 수납장에 들어있는 총 서류 묶음 숫자를 알려줍니다.
    def size(self):
        """저장된 고유 키의 총 개수를 반환합니다."""
        # [1차]: _size 값을 반환합니다.
        # [2차]: 기록된 장부 숫자를 말합니다.
        return self._size

    # [1차]: 현재 할당된 총 버킷 배열의 크기를 반환합니다.
    # [2차]: 수납장에 설치된 우편함 칸수가 총 몇 칸인지 알려줍니다.
    def capacity(self):
        """현재 버킷 배열의 크기를 반환합니다."""
        # [1차]: _capacity 값을 반환합니다.
        # [2차]: 우편함 칸수를 반환합니다.
        return self._capacity

    # [1차]: 현재 로드 팩터(size / capacity)를 부동소수점 값으로 반환합니다.
    # [2차]: 수납장이 현재 몇 %나 차 있는지 포화도를 알려줍니다.
    def load_factor(self):
        """현재 해시맵의 로드 팩터를 반환합니다."""
        # [1차]: 크기를 용량으로 나눈 비율을 계산합니다.
        # [2차]: 서류 수 / 우편함 수 비율을 구합니다.
        return self._size / self._capacity

    # [1차]: 버킷 크기를 2배로 확장하고 기존 모든 노드를 재해싱하여 재배치합니다.
    # [2차]: 우편함 16칸이 꽉 찼으니 32칸짜리 새 수납장으로 서류를 전부 이사시킵니다.
    def _resize(self, new_capacity):
        """
        버킷 크기를 변경하고 모든 기존 항목을 재해싱(Rehashing)하여 재배치합니다.
        """
        # [1차]: 기존 버킷 배열 참조를 보관합니다.
        # [2차]: 헌 수납장의 서류들을 잠시 이삿짐 상자에 담아둡니다.
        old_buckets = self._buckets
        # [1차]: 용량을 새 크기로 업데이트합니다.
        # [2차]: 수납장 칸수 규격을 32칸으로 갱신합니다.
        self._capacity = new_capacity
        # [1차]: 새 크기의 빈 버킷 배열을 새로 생성합니다.
        # [2차]: 32칸짜리 깨끗한 새 우편함 수납장을 설치합니다.
        self._buckets = [DoublyLinkedList() for _ in range(self._capacity)]
        # [1차]: put 메서드 호출 시 크기가 다시 누적되므로 0으로 리셋합니다.
        # [2차]: 서류를 새로 꽂을 때마다 다시 셀 수 있게 장부를 0으로 비웁니다.
        self._size = 0  # put 호출 시 다시 1씩 증가

        # [1차]: 기존 버킷들을 순회합니다.
        # [2차]: 헌 수납장 칸들을 차례대로 비웁니다.
        for bucket in old_buckets:
            # [1차]: 기존 버킷 내의 노드들을 순회합니다.
            # [2차]: 서류 봉투들을 하나씩 꺼냅니다.
            for node in bucket:
                # [1차]: 새 버킷 크기에 맞춰 다시 해싱하여 삽입합니다.
                # [2차]: 새 32칸 우편함 규칙에 맞춰 서류를 알맞은 새 칸에 착착 꽂습니다.
                self.put(node.key, node.value)

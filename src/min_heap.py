# [1차]: 최소 힙(Min Heap) 모듈을 정의합니다.
# [2차]: 가장 작은 숫자(가장 임박한 만료 시각)가 언제나 꼭대기에 올라오는 피라미드 진열대를 만듭니다.
"""
최소 힙 (Min Heap) 모듈
dict, set, collections 없이 동적 배열(list)을 완전 이진 트리 구조로 사용하여 구현합니다.
TTL 만료 관리를 위한 (expire_at, key) 형태의 요소를 효율적으로 처리합니다.
"""

# [1차]: 완전 이진 트리 배열 기반의 MinHeap 클래스를 선언합니다.
# [2차]: 편의점 유통기한 우선 진열대 클래스입니다.
class MinHeap:
    """
    최소 힙 (Min-Heap)
    - 주요 메서드: push, pop, peek, size
    - 내부 복원 알고리즘: _heapify_up, _heapify_down
    """
    # [1차]: MinHeap 인스턴스를 초기화하며 빈 내부 리스트를 할당합니다.
    # [2차]: 피라미드 진열대 바닥판을 깨끗하게 비워둡니다.
    def __init__(self):
        # [1차]: 트리 노드들을 평면 배열로 저장할 _data 리스트를 초기화합니다.
        # [2차]: 피라미드 층별로 상품을 나열할 일렬 받침대를 둡니다.
        self._data = []

    # [1차]: 새 요소를 힙 맨 끝에 추가한 후 상향 힙 복원(_heapify_up)을 수행합니다.
    # [2차]: 새 물건을 진열대 맨 끝에 두고, 유통기한이 더 빠르면 위층으로 올려보냅니다.
    def push(self, item):
        """
        새 요소를 힙에 삽입하고 상향 힙 복원(_heapify_up)을 수행합니다.
        시간 복잡도: O(log N)
        """
        # [1차]: 내부 배열의 맨 마지막 위치에 item을 추가합니다.
        # [2차]: 진열대 맨 끝자리에 새 삼각김밥을 올려놓습니다.
        self._data.append(item)
        # [1차]: 새로 추가된 요소의 인덱스에서부터 _heapify_up을 시작합니다.
        # [2차]: 새 삼각김밥을 위층 김밥들과 비교하며 꼭대기를 향해 엘리베이터를 태웁니다.
        self._heapify_up(len(self._data) - 1)

    # [1차]: 힙의 최솟값(루트 노드)을 제거하고 반환하며 하향 힙 복원(_heapify_down)을 수행합니다.
    # [2차]: 진열대 꼭대기(가장 유통기한 임박)의 상품을 꺼내고 피라미드를 다시 정돈합니다.
    def pop(self):
        """
        최솟값(루트 노드)을 제거하고 반환합니다.
        힙이 비어있으면 None을 반환합니다.
        시간 복잡도: O(log N)
        """
        # [1차]: 힙이 비어있는지 확인합니다.
        # [2차]: 진열대에 상품이 하나도 없는지 봅니다.
        if self.is_empty():
            # [1차]: 비어있으면 None을 반환합니다.
            # [2차]: 줄 상품이 없으니 빈손으로 돌아옵니다.
            return None

        # [1차]: 요소가 1개뿐인 경우 pop으로 즉시 꺼내어 반환합니다.
        # [2차]: 딱 1개 남아있으면 뒤처리할 것도 없이 그냥 꺼내줍니다.
        if len(self._data) == 1:
            # [1차]: 유일한 요소를 꺼내 반환합니다.
            # [2차]: 하나뿐인 물건을 건넵니다.
            return self._data.pop()

        # [1차]: 0번 인덱스(루트)의 최솟값을 임시 보관합니다.
        # [2차]: 꼭대기 1등 상품을 따로 챙겨둡니다.
        root = self._data[0]
        # [1차]: 맨 끝의 요소를 꺼내어 루트 노드 위치에 덮어씁니다.
        # [2차]: 진열대 맨 밑바닥에 있던 상품을 꼭대기 빈자리로 휙 옮겨놓습니다.
        self._data[0] = self._data.pop()
        # [1차]: 루트 노드에서부터 하향 힙 복원(_heapify_down)을 수행합니다.
        # [2차]: 꼭대기로 올라온 상품을 아래층 상품들과 비교하며 알맞은 층까지 아래로 내립니다.
        self._heapify_down(0)
        # [1차]: 추출된 루트 요소를 반환합니다.
        # [2차]: 아까 챙겨둔 1등 상품을 손님에게 건넵니다.
        return root

    # [1차]: 루트 노드의 최솟값을 제거하지 않고 O(1) 시간에 확인합니다.
    # [2차]: 꼭대기에 있는 상품을 꺼내지 않고 유통기한만 슬쩍 곁눈질로 봅니다.
    def peek(self):
        """
        최솟값(루트 노드)을 제거하지 않고 확인합니다.
        힙이 비어있으면 None을 반환합니다.
        시간 복잡도: O(1)
        """
        # [1차]: 힙이 비어있으면 None을 반환합니다.
        # [2차]: 진열대가 비어있으면 아무것도 없다고 알립니다.
        if self.is_empty():
            # [1차]: None 반환
            # [2차]: 빈손 알림
            return None
        # [1차]: 0번 인덱스의 루트 요소를 반환합니다.
        # [2차]: 꼭대기 물건을 보여줍니다.
        return self._data[0]

    # [1차]: 힙에 저장된 총 요소의 개수를 반환합니다.
    # [2차]: 진열대 위에 놓인 총 상품 숫자를 알려줍니다.
    def size(self):
        """힙에 저장된 총 요소 개수를 반환합니다."""
        # [1차]: _data 리스트의 길이를 반환합니다.
        # [2차]: 물건 총 개수를 셉니다.
        return len(self._data)

    # [1차]: 힙이 비어있는지 여부를 불리언 값으로 반환합니다.
    # [2차]: 진열대에 물건이 0개인지 묻는 질문에 답합니다.
    def is_empty(self):
        """힙이 비어있는지 확인합니다."""
        # [1차]: 길이가 0인지 비교합니다.
        # [2차]: 텅 비었는지 확인합니다.
        return len(self._data) == 0

    # [1차]: 특정 인덱스의 요소를 부모와 비교하며 상향 이동시킵니다.
    # [2차]: 상품이 위층 상품보다 더 긴급하면 윗자리와 맞바꾸며 엘리베이터를 타고 올라갑니다.
    def _heapify_up(self, index):
        """
        새로 삽입된 요소를 부모와 비교하며 적절한 위치까지 위로 끌어올립니다.
        부모 인덱스: (index - 1) // 2
        """
        # [1차]: 루트(0번)에 도달할 때까지 상향 순회합니다.
        # [2차]: 꼭대기 층에 닿을 때까지 계속 올라가 봅니다.
        while index > 0:
            # [1차]: 부모 노드의 인덱스를 계산합니다: (index - 1) // 2
            # [2차]: 내 바로 윗층 부모 칸 번호를 계산합니다.
            parent_idx = (index - 1) // 2
            # [1차]: 현재 노드가 부모 노드보다 값이 작은지(우선순위가 높은지) 비교합니다.
            # [2차]: 내 유통기한이 윗층 물건보다 더 임박했는지 비교합니다.
            if self._data[index] < self._data[parent_idx]:
                # [1차]: 자식 노드와 부모 노드의 위치를 스왑(맞교환)합니다.
                # [2차]: 더 급한 내 물건을 윗층으로 올리고 윗층 물건을 아래로 내립니다.
                self._data[index], self._data[parent_idx] = self._data[parent_idx], self._data[index]
                # [1차]: 인덱스를 부모 위치로 갱신하여 상향 추적을 이어갑니다.
                # [2차]: 내 위치가 윗층으로 올라갔으니 그 위치에서 다시 검사를 준비합니다.
                index = parent_idx
            else:
                # [1차]: 부모보다 작지 않으면 힙 불변성이 만족되므로 루프를 탈출합니다.
                # [2차]: 윗층 물건이 나보다 더 급한 물건이니 현재 층에 얌전히 멈춥니다.
                break

    # [1차]: 특정 인덱스의 요소를 자식들과 비교하며 하향 이동시킵니다.
    # [2차]: 꼭대기로 올라온 엉뚱한 상품을 아래층 더 급한 상품들과 비교하며 알맞은 층으로 내립니다.
    def _heapify_down(self, index):
        """
        루트 또는 특정 위치의 요소를 자식들과 비교하며 적절한 위치까지 아래로 내립니다.
        좌측 자식: 2 * index + 1
        우측 자식: 2 * index + 2
        """
        # [1차]: 배열의 총 길이를 캐싱합니다.
        # [2차]: 진열대 바닥 칸 번호 한계를 적어둡니다.
        length = len(self._data)
        # [1차]: 적절한 위치를 찾을 때까지 무한 루프로 하향 탐색합니다.
        # [2차]: 제자리를 찾을 때까지 에스컬레이터를 타고 내려갑니다.
        while True:
            # [1차]: 좌측 자식의 인덱스를 계산합니다: 2 * index + 1
            # [2차]: 왼쪽 아래 자식 칸 번호를 계산합니다.
            left_child_idx = 2 * index + 1
            # [1차]: 우측 자식의 인덱스를 계산합니다: 2 * index + 2
            # [2차]: 오른쪽 아래 자식 칸 번호를 계산합니다.
            right_child_idx = 2 * index + 2
            # [1차]: 현재 자신과 두 자식 중 가장 작은 요소의 인덱스를 추적합니다.
            # [2차]: 나, 왼쪽 자식, 오른쪽 자식 셋 중 유통기한 1등을 찾기 위한 표식입니다.
            smallest_idx = index

            # [1차]: 좌측 자식이 존재하고 현재 최솟값보다 더 작으면 갱신합니다.
            # [2차]: 왼쪽 자식이 존재하고 나보다 유통기한이 더 급하면 1등 후보로 지목합니다.
            if left_child_idx < length and self._data[left_child_idx] < self._data[smallest_idx]:
                # [1차]: smallest_idx를 좌측 자식 인덱스로 변경합니다.
                # [2차]: 왼쪽 자식을 1등 후보로 바꿉니다.
                smallest_idx = left_child_idx

            # [1차]: 우측 자식이 존재하고 현재 최솟값보다 더 작으면 갱신합니다.
            # [2차]: 오른쪽 자식이 존재하고 지금까지의 1등 후보보다 더 급하면 새 1등으로 지목합니다.
            if right_child_idx < length and self._data[right_child_idx] < self._data[smallest_idx]:
                # [1차]: smallest_idx를 우측 자식 인덱스로 변경합니다.
                # [2차]: 오른쪽 자식을 1등 후보로 바꿉니다.
                smallest_idx = right_child_idx

            # [1차]: 가장 작은 요소가 자기 자신이 아니라면 스왑하고 계속 내려갑니다.
            # [2차]: 자식들 중에 나보다 더 급한 물건이 있다면 자리를 맞바꿔주고 더 내려갑니다.
            if smallest_idx != index:
                # [1차]: 현재 노드와 smallest_idx 노드를 스왑합니다.
                # [2차]: 더 급한 자식 상품을 위로 올리고 내 상품을 아래로 내립니다.
                self._data[index], self._data[smallest_idx] = self._data[smallest_idx], self._data[index]
                # [1차]: 인덱스를 smallest_idx로 갱신하여 하향 순회를 이어갑니다.
                # [2차]: 내려간 새 층에서 다음 자식들과 다시 비교를 준비합니다.
                index = smallest_idx
            else:
                # [1차]: 자신이 자식들보다 모두 작거나 같으면 힙 정렬이 완성되었으므로 종료합니다.
                # [2차]: 내가 자식들보다 더 급한 물건이거나 바닥에 도착했으니 이 층에 자리를 잡습니다.
                break

# [1차]: 이중 연결 리스트(Doubly Linked List) 모듈을 정의합니다.
# [2차]: 앞사람과 뒷사람의 손을 양쪽으로 붙잡고 늘어선 아이들의 기차 대형을 만듭니다.
"""
이중 연결 리스트 (Doubly Linked List) 모듈
dict, set, collections 없이 O(1) 삽입, 삭제, 이동 연산을 제공합니다.
"""

# [1차]: 개별 데이터와 양방향 링크(포인터)를 저장하는 Node 클래스를 선언합니다.
# [2차]: 기차 대형에서 앞뒤 친구의 손을 잡고 명찰을 달고 있는 개별 학생입니다.
class Node:
    """이중 연결 리스트 노드"""
    # [1차]: 노드 인스턴스를 초기화하며 key, value, data 및 이전/다음 포인터를 설정합니다.
    # [2차]: 학생이 가방에 물건(key, value)을 챙기고 앞뒤 손을 잡을 준비를 마칩니다.
    def __init__(self, key=None, value=None, data=None):
        # [1차]: 노드가 보유할 고유 식별자 key를 할당합니다.
        # [2차]: 사물함 번호나 이름표 명찰을 가슴에 답니다.
        self.key = key
        # [1차]: 노드가 보유할 데이터 값 value를 할당합니다.
        # [2차]: 이름표 뒤에 적힌 실제 연락처나 알맹이 정보입니다.
        self.value = value
        # [1차]: data 인자가 전달되면 우선 적용하고, 없으면 (key, value) 튜플로 기본 생성합니다.
        # [2차]: 종합 선물세트 상자에 키와 값을 한 번에 담아 보관합니다.
        self.data = data if data is not None else (key, value)
        # [1차]: 이전 노드를 가리키는 포인터 prev를 None으로 초기화합니다.
        # [2차]: 왼손으로 앞사람 옷자락을 잡기 전 손을 비워둡니다.
        self.prev = None
        # [1차]: 다음 노드를 가리키는 포인터 next를 None으로 초기화합니다.
        # [2차]: 오른손으로 뒷사람 옷자락을 잡기 전 손을 비워둡니다.
        self.next = None

    # [1차]: 객체의 문자열 표현형을 반환하여 디버깅을 용이하게 합니다.
    # [2차]: 학생의 이름표를 사람이 읽기 쉬운 글자로 보여줍니다.
    def __repr__(self):
        # [1차]: key와 value를 포맷팅한 문자열을 반환합니다.
        # [2차]: "저는 누구이고 어떤 값을 가지고 있어요"라고 자기소개합니다.
        return f"Node(key={self.key}, value={self.value})"


# [1차]: 센티넬 더미 노드를 기반으로 O(1) 연산을 보장하는 이중 연결 리스트 클래스를 선언합니다.
# [2차]: 출발선(Head)과 도착선(Tail) 깃발이 양 끝에 꽂혀 있는 안전한 달리기 트랙입니다.
class DoublyLinkedList:
    """
    더미 헤드(dummy head)와 더미 테일(dummy tail)을 사용하는 원자적 O(1) 이중 연결 리스트
    """
    # [1차]: DoublyLinkedList 인스턴스를 초기화하고 더미 헤드와 테일을 연결합니다.
    # [2차]: 트랙을 개장하고 출발선 기둥과 결승선 기둥을 줄로 단단히 이어둡니다.
    def __init__(self):
        # [1차]: 센티넬 더미 헤드 노드를 생성합니다.
        # [2차]: 달리기 트랙의 절대 움직이지 않는 출발 깃발 기둥입니다.
        self.head = Node()
        # [1차]: 센티넬 더미 테일 노드를 생성합니다.
        # [2차]: 달리기 트랙의 절대 움직이지 않는 도착 깃발 기둥입니다.
        self.tail = Node()
        # [1차]: 더미 헤드의 next 포인터가 더미 테일을 가리키도록 설정합니다.
        # [2차]: 출발 기둥의 밧줄을 도착 기둥으로 곧바로 연결합니다.
        self.head.next = self.tail
        # [1차]: 더미 테일의 prev 포인터가 더미 헤드를 가리키도록 설정합니다.
        # [2차]: 도착 기둥에서 되돌아보는 밧줄을 출발 기둥으로 맞물립니다.
        self.tail.prev = self.head
        # [1차]: 현재 저장된 실제 유효 노드의 개수를 나타내는 _size를 0으로 초기화합니다.
        # [2차]: 트랙 위를 달리는 실제 주자 수를 0명으로 기록합니다.
        self._size = 0

    # [1차]: 리스트의 맨 앞(head 바로 다음)에 노드를 O(1) 복잡도로 삽입합니다.
    # [2차]: 새 주자를 출발선 바로 맨 앞 1등 자리로 새치기시켜 합류시킵니다.
    def insert_front(self, node):
        # [1차]: 인자가 Node 객체가 아닌 경우 Node로 감싸서 인스턴스화합니다.
        # [2차]: 번호표를 안 단 주자에게 즉석에서 명찰과 번호표를 달아줍니다.
        if not isinstance(node, Node):
            # [1차]: 전달된 data를 기반으로 새 Node 인스턴스를 생성합니다.
            # [2차]: 새 선수의 옷에 등번호를 새겨 유니폼을 완성합니다.
            node = Node(data=node)

        # [1차]: 현재 더미 헤드의 바로 뒤에 위치한 첫 번째 유효 노드를 임시 참조합니다.
        # [2차]: 지금까지 출발선 바로 뒤에서 1등으로 서 있던 친구를 확인합니다.
        first = self.head.next
        # [1차]: 새 노드의 prev 포인터가 더미 헤드를 가리키게 합니다.
        # [2차]: 새 선수의 왼손으로 출발 기둥을 꼭 쥡니다.
        node.prev = self.head
        # [1차]: 새 노드의 next 포인터가 기존 첫 번째 노드를 가리키게 합니다.
        # [2차]: 새 선수의 오른손으로 기존 1등 친구의 손을 잡습니다.
        node.next = first
        # [1차]: 더미 헤드의 next 포인터가 새 노드를 가리키게 갱신합니다.
        # [2차]: 출발 기둥의 밧줄을 이제 새 선수에게 넘깁니다.
        self.head.next = node
        # [1차]: 기존 첫 번째 노드의 prev 포인터가 새 노드를 가리키게 갱신합니다.
        # [2차]: 기존 1등 친구의 왼손으로 새 선수의 손을 꼭 맞잡게 합니다.
        first.prev = node
        # [1차]: 저장된 유효 노드 개수를 1 증가시킵니다.
        # [2차]: 경기장의 출전 선수 명수 카운트를 1 올립니다.
        self._size += 1
        # [1차]: 삽입된 노드 객체를 반환합니다.
        # [2차]: 방금 합류한 선수를 가리켜 안내합니다.
        return node

    # [1차]: 리스트의 맨 뒤(tail 바로 이전)에 노드를 O(1) 복잡도로 삽입합니다.
    # [2차]: 새 주자를 결승선 바로 직전 맨 꼴찌 자리로 줄 서게 합니다.
    def insert_back(self, node):
        # [1차]: 인자가 Node 객체가 아니면 Node 인스턴스로 자동 래핑합니다.
        # [2차]: 명찰이 없는 사람에게 정식 선수 명찰을 달아줍니다.
        if not isinstance(node, Node):
            # [1차]: 전달된 데이터를 바탕으로 Node를 생성합니다.
            # [2차]: 번호표를 새로 발급합니다.
            node = Node(data=node)

        # [1차]: 현재 더미 테일의 바로 이전에 위치한 마지막 유효 노드를 임시 참조합니다.
        # [2차]: 지금까지 맨 꼴찌로 서 있던 친구를 확인합니다.
        last = self.tail.prev
        # [1차]: 새 노드의 prev 포인터가 기존 마지막 노드를 가리키게 합니다.
        # [2차]: 새 주자의 왼손으로 기존 꼴찌 친구의 손을 잡습니다.
        node.prev = last
        # [1차]: 새 노드의 next 포인터가 더미 테일을 가리키게 합니다.
        # [2차]: 새 주자의 오른손으로 결승선 기둥을 잡습니다.
        node.next = self.tail
        # [1차]: 기존 마지막 노드의 next 포인터가 새 노드를 가리키게 합니다.
        # [2차]: 기존 꼴찌 친구의 오른손을 새 주자에게 넘겨줍니다.
        last.next = node
        # [1차]: 더미 테일의 prev 포인터가 새 노드를 가리키게 갱신합니다.
        # [2차]: 결승선 기둥의 밧줄을 새 주자에게로 연결합니다.
        self.tail.prev = node
        # [1차]: 유효 노드 카운트를 1 증가시킵니다.
        # [2차]: 선수 명수를 1 올립니다.
        self._size += 1
        # [1차]: 삽입된 노드를 반환합니다.
        # [2차]: 방금 줄 선 주자를 반환합니다.
        return node

    # [1차]: 임의의 특정 노드를 O(1) 시간에 리스트의 연결 고리에서 제거합니다.
    # [2차]: 행렬 한가운데 있는 친구가 손을 놓고 조용히 대열에서 빠져나갑니다.
    def remove_node(self, node):
        # [1차]: 전달된 노드가 None이거나 포인터가 유효하지 않은 경우 무시하고 None을 반환합니다.
        # [2차]: 존재하지도 않는 허깨비를 빼내려고 하면 헛손질을 막습니다.
        if node is None or node.prev is None or node.next is None:
            # [1차]: 실패를 의미하는 None을 반환합니다.
            # [2차]: 아무 작업도 하지 않고 빈손으로 돌아옵니다.
            return None
        
        # [1차]: 센티넬 더미 노드(head, tail)는 절대 삭제되지 않도록 방어합니다.
        # [2차]: 출발 깃발 기둥이나 결승선 기둥을 뽑아가려는 시도를 철저히 차단합니다.
        if node is self.head or node is self.tail:
            # [1차]: None을 반환하여 보호합니다.
            # [2차]: 기둥 파손을 막고 종료합니다.
            return None

        # [1차]: 제거 대상 노드의 이전 노드를 변수에 보관합니다.
        # [2차]: 빠져나갈 친구의 앞사람을 확인합니다.
        prev_node = node.prev
        # [1차]: 제거 대상 노드의 다음 노드를 변수에 보관합니다.
        # [2차]: 빠져나갈 친구의 뒷사람을 확인합니다.
        next_node = node.next
        # [1차]: 이전 노드의 next 포인터가 다음 노드를 직접 가리키도록 건너뜁니다.
        # [2차]: 앞사람이 친구를 건너뛰어 뒷사람의 손을 직접 덥석 잡습니다.
        prev_node.next = next_node
        # [1차]: 다음 노드의 prev 포인터가 이전 노드를 직접 가리키도록 건너뜁니다.
        # [2차]: 뒷사람도 친구를 건너뛰어 앞사람의 손을 맞잡습니다.
        next_node.prev = prev_node

        # [1차]: 분리된 노드의 prev 링크를 None으로 해제합니다.
        # [2차]: 대열에서 나온 친구의 왼손을 깨끗이 씻습니다.
        node.prev = None
        # [1차]: 분리된 노드의 next 링크를 None으로 해제합니다.
        # [2차]: 대열에서 나온 친구의 오른손을 깨끗이 씻습니다.
        node.next = None
        # [1차]: 리스트의 크기를 1 감소시킵니다.
        # [2차]: 출전 주자 수 카운트를 1 차감합니다.
        self._size -= 1
        # [1차]: 분리된 노드 객체를 반환합니다.
        # [2차]: 대열을 떠난 주자를 밖으로 모셔옵니다.
        return node

    # [1차]: 맨 앞 유효 노드를 제거하고 반환합니다.
    # [2차]: 출발선 바로 뒤 1등 자리에 서 있던 주자를 밖으로 부릅니다.
    def remove_front(self):
        # [1차]: 리스트가 비어있는지 확인합니다.
        # [2차]: 트랙에 아무도 안 서 있는지 확인합니다.
        if self.is_empty():
            # [1차]: 비어있으면 None을 반환합니다.
            # [2차]: 데려올 사람이 없으니 빈손으로 돌아옵니다.
            return None
        # [1차]: 더미 헤드 바로 다음 노드를 remove_node로 삭제합니다.
        # [2차]: 1등 주자를 안전하게 대열에서 빼냅니다.
        return self.remove_node(self.head.next)

    # [1차]: 맨 뒤 유효 노드를 제거하고 반환합니다.
    # [2차]: 결승선 바로 앞 맨 꼴찌 자리에 서 있던 주자를 밖으로 부릅니다.
    def remove_back(self):
        # [1차]: 리스트가 비어있는지 검사합니다.
        # [2차]: 달리는 사람이 없는지 확인합니다.
        if self.is_empty():
            # [1차]: 비어있으면 None을 반환합니다.
            # [2차]: 뺄 사람이 없으니 빈손으로 돌아옵니다.
            return None
        # [1차]: 더미 테일 바로 이전 노드를 remove_node로 삭제합니다.
        # [2차]: 맨 꼴찌 주자를 안전하게 대열에서 뺍니다.
        return self.remove_node(self.tail.prev)

    # [1차]: 주어진 노드를 현재 위치에서 떼어내 맨 앞(head 바로 뒤)으로 O(1) 이동시킵니다.
    # [2차]: 달리기 중간에 있던 선수를 출발선 바로 뒤 최선두 자리로 순간이동시킵니다.
    def move_to_front(self, node):
        # [1차]: 노드가 없거나 센티넬 노드인 경우 연산을 중단합니다.
        # [2차]: 유령이거나 출발/결승선 기둥이면 이동시키지 않습니다.
        if node is None or node is self.head or node is self.tail:
            # [1차]: 함수를 즉시 종료합니다.
            # [2차]: 그대로 둡니다.
            return
        # [1차]: 이미 맨 앞에 있는 경우 불필요한 포인터 조작을 건너뜁니다.
        # [2차]: 이미 1등 자리에 서 있으면 굳이 움직이지 않습니다.
        if self.head.next is node:
            # [1차]: 조기 종료합니다.
            # [2차]: 제자리에 둡니다.
            return
        
        # [1차]: 노드의 원래 양옆 이웃 노드를 파악합니다.
        # [2차]: 이 선수가 서 있던 자리의 앞뒤 친구들을 봅니다.
        prev_node = node.prev
        # [1차]: 노드의 원래 다음 노드를 파악합니다.
        # [2차]: 뒷사람을 봅니다.
        next_node = node.next
        # [1차]: 원래 이웃 노드끼리 손을 잇습니다.
        # [2차]: 빠져나간 빈자리를 메우기 위해 앞뒤 친구가 손을 다시 잡습니다.
        prev_node.next = next_node
        # [1차]: 원래 이웃 노드끼리 역방향 손을 잇습니다.
        # [2차]: 뒷사람도 앞사람 손을 잡습니다.
        next_node.prev = prev_node

        # [1차]: 현재 1등 노드를 임시 저장합니다.
        # [2차]: 출발선 바로 뒤에 있던 현재 1등 친구를 확인합니다.
        first = self.head.next
        # [1차]: 노드의 prev를 더미 헤드로 연결합니다.
        # [2차]: 이동한 선수의 왼손으로 출발 깃발을 잡습니다.
        node.prev = self.head
        # [1차]: 노드의 next를 기존 1등 노드로 연결합니다.
        # [2차]: 이동한 선수의 오른손으로 기존 1등 친구의 손을 잡습니다.
        node.next = first
        # [1차]: 더미 헤드의 next를 해당 노드로 갱신합니다.
        # [2차]: 출발 깃발의 밧줄을 이제 이 선수에게 연결합니다.
        self.head.next = node
        # [1차]: 기존 1등 노드의 prev를 해당 노드로 갱신합니다.
        # [2차]: 기존 1등 친구가 새 선수의 손을 잡습니다.
        first.prev = node

    # [1차]: 리스트의 총 노드 수를 반환합니다.
    # [2차]: 트랙 위에서 달리고 있는 전체 선수의 머릿수를 알려줍니다.
    def size(self):
        # [1차]: 내부 크기 변수 _size를 반환합니다.
        # [2차]: 기록해둔 주자 숫자를 말해줍니다.
        return self._size

    # [1차]: 리스트가 비어있는지 여부를 불리언 값으로 반환합니다.
    # [2차]: 운동장에 주자가 0명인지 묻는 질문에 참/거짓으로 답합니다.
    def is_empty(self):
        # [1차]: _size가 0인지 비교합니다.
        # [2차]: 텅 비었는지 확인합니다.
        return self._size == 0

    # [1차]: 리스트의 노드들을 순회하여 파이썬 기본 리스트로 변환합니다.
    # [2차]: 줄 서 있는 모든 선수들의 명단을 종이에 순서대로 적어 뽑아냅니다.
    def to_list(self):
        # [1차]: 결과를 담을 빈 리스트를 초기화합니다.
        # [2차]: 깨끗한 백지 명부를 준비합니다.
        result = []
        # [1차]: 첫 번째 유효 노드부터 순회를 시작합니다.
        # [2차]: 1등 주자부터 시작합니다.
        curr = self.head.next
        # [1차]: 더미 테일에 도달할 때까지 포인터를 전진합니다.
        # [2차]: 결승선 기둥에 닿을 때까지 다음 사람으로 걸어갑니다.
        while curr is not self.tail:
            # [1차]: 현재 노드를 결과 리스트에 추가합니다.
            # [2차]: 명부에 주자 이름을 한 줄 적습니다.
            result.append(curr)
            # [1차]: 다음 노드로 이동합니다.
            # [2차]: 뒷사람에게로 발걸음을 옮깁니다.
            curr = curr.next
        # [1차]: 수집된 노드 리스트를 반환합니다.
        # [2차]: 완성된 명부를 건넵니다.
        return result

    # [1차]: 파이썬의 for ... in 문에서 직접 순회할 수 있도록 이터레이터를 구현합니다.
    # [2차]: 손님들이 줄 선 선수들을 앞에서부터 한 명씩 차례대로 만나볼 수 있게 합니다.
    def __iter__(self):
        # [1차]: 첫 번째 유효 노드를 시작점으로 잡습니다.
        # [2차]: 맨 앞 1등 주자부터 섭외합니다.
        curr = self.head.next
        # [1차]: 더미 테일 이전까지 반복합니다.
        # [2차]: 결승선 직전까지 한 명씩 넘깁니다.
        while curr is not self.tail:
            # [1차]: 현재 노드를 yield로 방출합니다.
            # [2차]: 이번 주자를 차례대로 호명합니다.
            yield curr
            # [1차]: 다음 노드로 포인터를 이동합니다.
            # [2차]: 다음 주자를 찾아갑니다.
            curr = curr.next
